"""Writes assets/astronomy/ASSET_CATALOG.md and ASSET_DOWNLOAD_LOG.md from the manifest
and the download log produced by tools/acquire_assets.py (plus the data assets)."""
import json
import os

LIB = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "astronomy")
STAGE = {"1-2": "Molecular cloud / collapse", "3-4": "Protostar / disc and jets", "5": "Main sequence (Sun)",
         "6": "Final stage", "": "Reference only (not linked)"}
EXTRA = [  # data assets acquired separately (see assets/data/*/*.json)
    ("hmi-cr2284", "SDO/HMI synoptic radial magnetogram, CR 2284 (2024 May 6 - Jun 2)", "solar_photosphere",
     "NASA/SDO, HMI; JSOC", "http://jsoc.stanford.edu/data/hmi/synoptic/", "3600x1440 FITS (float32)",
     "Fe I 617.3 nm Zeeman polarimetry", "observation (measured field)", "Public domain (NASA); courtesy credit",
     "Drives sunspots, plage, flare site, prominence anchors and coronal brightening (baked: assets/data/sun)"),
    ("casa-3d", "Cassiopeia A 3D reconstruction (ASCII VTK iso-surfaces)", "volumetric_datasets",
     "NASA/CXC/SAO; Delaney et al. 2010", "https://chandra.harvard.edu/tactile/3d_printing.html", "7 VTK surfaces",
     "X-ray Si/Fe (Chandra), IR Ar/Ne (Spitzer), optical Doppler", "observation-derived 3D reconstruction",
     "No copyright asserted (CXC); NASA guidelines", "Neutron-star remnant ejecta volume (baked at build time)"),
    ("eso0932a", "Milky Way panorama (6000x3000)", "textures", "ESO/S. Brunier",
     "https://www.eso.org/public/images/eso0932a/", "6000x3000 JPEG", "visible", "observation (photographic mosaic)",
     "CC BY 4.0", "Background sky of every stage (assets/sky)"),
]


def main():
    man = json.load(open(os.path.join(LIB, "metadata", "manifest.json"), encoding="utf-8"))
    rows = sorted(man.values(), key=lambda r: (r["category"], r["id"]))
    with open(os.path.join(LIB, "ASSET_CATALOG.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# STELLARIS Astronomy Reference Library — Catalogue\n\n"
                "Generated by `tools/write_catalog.py` from `metadata/manifest.json` (per-file SHA-256, URL, credit).\n"
                "Files are downloaded by `tools/acquire_assets.py` and are not committed (size); the manifest is.\n"
                "Kind: unless stated, entries are processed observatory images. Titles that say *artist's impression*,\n"
                "*illustration* or *simulation* are not observations; they are excluded from the Observation view.\n"
                "Type Ia remnants (Tycho, Kepler) are reference only: STELLARIS follows single stars, and a Type Ia\n"
                "supernova needs a white dwarf in a binary.\n\n")
        f.write("## Data and texture assets used by the engine\n\n| ID | Asset | Category | Source | Format | Band | Kind | Licence | Use |\n|---|---|---|---|---|---|---|---|---|\n")
        for e in EXTRA:
            f.write(f"| {e[0]} | {e[1]} | {e[2]} | [{e[3]}]({e[4]}) | {e[5]} | {e[6]} | {e[7]} | {e[8]} | {e[9]} |\n")
        cat = None
        for r in rows:
            if r["category"] != cat:
                cat = r["category"]
                f.write(f"\n## {cat}\n\n| ID | Title | Source | Resolution | MiB | Band / instrument | Stage | Credit | Licence |\n|---|---|---|---|---|---|---|---|---|\n")
            band = r.get("band", "see source page")
            stage = STAGE.get(r.get("stage", ""), r.get("stage", "")) + (f" ({r['pathway']})" if r.get("pathway") not in ("all", None) else "")
            f.write(f"| {r['id']} | {r['title']} | [{r['organization']}]({r['source_page']}) | {r.get('dimensions', '')} | "
                    f"{r['bytes'] / 2**20:.1f} | {band} | {stage} | {r.get('credit', '')} | {r['license']} |\n")
        total = sum(r["bytes"] for r in rows) / 2**30
        f.write(f"\n{len(rows)} files, {total:.2f} GiB.\n")
    log_path = os.path.join(LIB, "metadata", "download_log.tsv")
    lines = open(log_path, encoding="utf-8").read().splitlines() if os.path.exists(log_path) else []
    with open(os.path.join(LIB, "ASSET_DOWNLOAD_LOG.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# STELLARIS Astronomy Reference Library — Download Log\n\n"
                "Every search and download attempt by `tools/acquire_assets.py` (UNAVAILABLE = no result whose title\n"
                "names the object; FAILED = network/HTTP error; SKIPPED = duplicate). Nothing is substituted silently.\n\n"
                "| Time | Status | Category | Site | Query / ID | Detail |\n|---|---|---|---|---|---|\n")
        for line in lines:
            c = line.split("\t")
            if len(c) >= 6:
                f.write("| " + " | ".join(x.replace("|", "/") for x in c[:6]) + " |\n")
    print("catalog written:", len(rows), "entries,", len(lines), "log lines")


if __name__ == "__main__":
    main()
